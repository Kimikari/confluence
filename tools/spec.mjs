#!/usr/bin/env node
// Bounded retrieval from docs/confluence/confluence-design.md.
//   node tools/spec.mjs toc                 chapters and rule sections with line ranges
//   node tools/spec.mjs show <ID|heading>   one section (e.g. SPL-009, WIZ-002, "Core reaction table")
//   node tools/spec.mjs lines <from> <to>   raw line range (1-based, inclusive)
//   node tools/spec.mjs grep <regex> [max]  matching lines with line numbers
//   node tools/spec.mjs index               write docs/SPEC_INDEX.md
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const specPath = path.join(root, 'docs', 'confluence', 'confluence-design.md');
const lines = fs.readFileSync(specPath, 'utf8').split(/\r?\n/);

function headings() {
  const hs = [];
  lines.forEach((l, i) => {
    const m = /^(#{1,4}) (.*)$/.exec(l);
    if (m) hs.push({ level: m[1].length, title: m[2].trim(), line: i + 1 });
  });
  for (let i = 0; i < hs.length; i++) {
    let end = lines.length;
    for (let j = i + 1; j < hs.length; j++) if (hs[j].level <= hs[i].level) { end = hs[j].line - 1; break; }
    hs[i].end = end;
  }
  return hs;
}

const isCatalogueEntry = (t) => /^(WIZ|SPL|EQP|AUG|BIO|MOD|PROP|BLD)-\d+/.test(t);

function toc() {
  return headings().filter((h) => h.level <= 3 && !isCatalogueEntry(h.title));
}

function find(query) {
  const hs = headings();
  const q = query.toLowerCase();
  return hs.find((h) => h.title.toLowerCase().startsWith(q + ' ') || h.title.toLowerCase() === q)
    || hs.find((h) => h.title.toLowerCase().includes(q));
}

const [cmd, ...args] = process.argv.slice(2);
switch (cmd) {
  case 'toc':
    for (const h of toc()) console.log(`${'  '.repeat(h.level - 1)}${h.title}  [${h.line}-${h.end}]`);
    break;
  case 'show': {
    const h = find(args.join(' '));
    if (!h) { console.error('not found'); process.exit(1); }
    console.log(`<!-- ${h.title} lines ${h.line}-${h.end} -->`);
    console.log(lines.slice(h.line - 1, h.end).join('\n'));
    break;
  }
  case 'lines': {
    const a = Math.max(1, +args[0]); const b = Math.min(lines.length, +args[1]);
    for (let i = a; i <= b; i++) console.log(`${i}: ${lines[i - 1]}`);
    break;
  }
  case 'grep': {
    const re = new RegExp(args[0], 'i'); const max = +(args[1] || 60); let n = 0;
    for (let i = 0; i < lines.length && n < max; i++) if (re.test(lines[i])) { console.log(`${i + 1}: ${lines[i].slice(0, 400)}`); n++; }
    break;
  }
  case 'index': {
    const hs = headings();
    const out = ['# Specification index', '', 'Generated by `node tools/spec.mjs index` from `docs/confluence/confluence-design.md`. Use `node tools/spec.mjs show <heading or ID>` to read one section.', '', '## Rule chapters and sections', ''];
    for (const h of toc()) out.push(`${'  '.repeat(h.level - 1)}- ${h.title} — lines ${h.line}-${h.end}`);
    out.push('', '## Catalogue entry ranges', '');
    const groups = {};
    for (const h of hs.filter((x) => x.level === 2 && isCatalogueEntry(x.title))) {
      const p = h.title.split('-')[0];
      (groups[p] ||= []).push(h);
    }
    for (const [p, list] of Object.entries(groups)) {
      out.push(`- ${p}: ${list.length} entries, lines ${list[0].line}-${list[list.length - 1].end} (first ${list[0].title}, last ${list[list.length - 1].title})`);
    }
    fs.writeFileSync(path.join(root, 'docs', 'SPEC_INDEX.md'), out.join('\n') + '\n');
    console.log('wrote docs/SPEC_INDEX.md');
    break;
  }
  default:
    console.log('usage: node tools/spec.mjs toc|show <q>|lines <a> <b>|grep <re> [max]|index');
}
