using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Confluence.Core.Content;
using Confluence.Core.Json;

namespace Confluence.Tools.Ledger
{
    /// <summary>Renders the ledger as docs/CONTENT_LEDGER.md and docs/content-ledger.json. Output is deterministic.</summary>
    public static class LedgerWriter
    {
        private static readonly (ContentType Type, string Title)[] Sections =
        {
            (ContentType.Wizard, "Wizards"),
            (ContentType.Spell, "Spells"),
            (ContentType.Equipment, "Equipment"),
            (ContentType.Augment, "Augments"),
            (ContentType.Biome, "Biomes"),
            (ContentType.Module, "Modules"),
            (ContentType.Prop, "Props"),
            (ContentType.Build, "Builds"),
        };

        public static string Markdown(Ledger ledger)
        {
            var cat = ledger.Catalogue;
            var sb = new StringBuilder();
            sb.AppendLine("# Content ledger");
            sb.AppendLine();
            sb.AppendLine("Generated by `src/Confluence.Tools.Ledger`; do not edit by hand. Regenerate with `powershell -ExecutionPolicy Bypass -File tools/ledger.ps1`, which runs");
            sb.AppendLine("`dotnet test Confluence.sln` with TRX logging into `out/test-results` and then the ledger tool with `--trx out/test-results`.");
            sb.AppendLine("Running `dotnet run --project src/Confluence.Tools.Ledger` without `--trx` rescans attributes but reports every verifying test as not run.");
            sb.AppendLine();
            sb.AppendLine("Catalogue: " + cat.Title + ", design version " + cat.DesignVersion + " (" + cat.Date + "). Scanned "
                + ledger.TestAssemblies.Count + " test assemblies (" + ledger.VerifyingTestCount + " test methods carry `[Verifies]`) and "
                + ledger.TrxFiles.Count + " TRX result files.");
            sb.AppendLine();

            sb.AppendLine("## Statuses");
            sb.AppendLine();
            sb.AppendLine("| Status | Meaning |");
            sb.AppendLine("| --- | --- |");
            sb.AppendLine("| unstarted | No class in the gameplay assemblies carries `[ContentBehavior(\"ID\")]`. Draft and shop pools exclude the record (DECISIONS D-010). |");
            sb.AppendLine("| implemented | A `[ContentBehavior(\"ID\")]` class exists, but no test carries `[Verifies(\"ID\")]`. |");
            sb.AppendLine("| implemented-tests-not-run | Implemented with verifying tests, but at least one has no executed result in the TRX files. |");
            sb.AppendLine("| implemented-tests-failing | Implemented, and at least one verifying test failed. |");
            sb.AppendLine("| verified | Implemented, and every verifying test ran and passed. |");
            sb.AppendLine();
            sb.AppendLine("Only catalogue IDs are tracked here. Feats (FEAT-001..024), casting grammars, and global systems are tracked in `docs/PROGRESS.md`.");
            sb.AppendLine();

            sb.AppendLine("## Summary");
            sb.AppendLine();
            sb.Append("| Type | Total |");
            foreach (var status in Ledger.AllStatuses) sb.Append(' ').Append(Ledger.Slug(status)).Append(" |");
            sb.AppendLine();
            sb.Append("| --- | ---: |");
            foreach (var _ in Ledger.AllStatuses) sb.Append(" ---: |");
            sb.AppendLine();
            foreach (var (type, title) in Sections) SummaryRow(sb, ledger, title, type);
            SummaryRow(sb, ledger, "**All**", null);
            sb.AppendLine();

            if (ledger.OutOfScopeIds.Count > 0 || ledger.UnknownIds.Count > 0 || ledger.Warnings.Count > 0)
            {
                sb.AppendLine("## Notes");
                sb.AppendLine();
                if (ledger.OutOfScopeIds.Count > 0) sb.AppendLine("- Attribute IDs outside per-ID tracking: " + string.Join(", ", ledger.OutOfScopeIds) + ".");
                if (ledger.UnknownIds.Count > 0) sb.AppendLine("- Attribute IDs missing from the catalogue: " + string.Join(", ", ledger.UnknownIds) + ".");
                foreach (var warning in ledger.Warnings) sb.AppendLine("- Warning: " + Cell(warning));
                sb.AppendLine();
            }

            sb.AppendLine("## Wizards and their spells");
            sb.AppendLine();
            foreach (var wizard in cat.Wizards)
            {
                var entry = ledger.ById[wizard.Id];
                sb.AppendLine("### " + wizard.Id + " " + wizard.Name + " - " + Ledger.Slug(entry.Status));
                sb.AppendLine();
                sb.AppendLine("| ID | Spell | School | Status | Evidence |");
                sb.AppendLine("| --- | --- | --- | --- | --- |");
                foreach (var spell in cat.SpellsOf(wizard.Id))
                    Row(sb, ledger.ById[spell.Id], spell.Name, spell.School);
                sb.AppendLine();
            }

            sb.AppendLine("## Equipment");
            sb.AppendLine();
            sb.AppendLine("| ID | Name | Category | Tier | Status | Evidence |");
            sb.AppendLine("| --- | --- | --- | ---: | --- | --- |");
            foreach (var item in cat.EquipmentItems)
                Row(sb, ledger.ById[item.Id], item.Name, item.CategoryText, item.Tier.ToString());
            sb.AppendLine();

            sb.AppendLine("## Augments");
            sb.AppendLine();
            sb.AppendLine("### Shared augments");
            sb.AppendLine();
            sb.AppendLine("| ID | Name | Family | Rarity | Status | Evidence |");
            sb.AppendLine("| --- | --- | --- | --- | --- | --- |");
            foreach (var augment in cat.SharedAugments)
                Row(sb, ledger.ById[augment.Id], augment.Name, augment.Family, augment.Rarity);
            sb.AppendLine();
            sb.AppendLine("### Spell transformations");
            sb.AppendLine();
            sb.AppendLine("| ID | Name | Wizard | Target | Rarity | Status | Evidence |");
            sb.AppendLine("| --- | --- | --- | --- | --- | --- | --- |");
            foreach (var augment in cat.Transformations)
                Row(sb, ledger.ById[augment.Id], augment.Name, augment.OwnerWizardId, augment.TargetSpellId, augment.Rarity);
            sb.AppendLine();

            sb.AppendLine("## Biomes");
            sb.AppendLine();
            sb.AppendLine("| ID | Name | Status | Evidence |");
            sb.AppendLine("| --- | --- | --- | --- |");
            foreach (var biome in cat.Biomes) Row(sb, ledger.ById[biome.Id], biome.Name);
            sb.AppendLine();

            sb.AppendLine("## Modules");
            sb.AppendLine();
            sb.AppendLine("| ID | Name | Category | Status | Evidence |");
            sb.AppendLine("| --- | --- | --- | --- | --- |");
            foreach (var module in cat.Modules) Row(sb, ledger.ById[module.Id], module.Name, module.CategoryText);
            sb.AppendLine();

            sb.AppendLine("## Props");
            sb.AppendLine();
            sb.AppendLine("| ID | Name | Category | Status | Evidence |");
            sb.AppendLine("| --- | --- | --- | --- | --- |");
            foreach (var prop in cat.Props) Row(sb, ledger.ById[prop.Id], prop.Name, prop.CategoryText);
            sb.AppendLine();

            sb.AppendLine("## Builds");
            sb.AppendLine();
            sb.AppendLine("| ID | Name | Wizard | Status | Evidence |");
            sb.AppendLine("| --- | --- | --- | --- | --- |");
            foreach (var build in cat.Builds) Row(sb, ledger.ById[build.Id], build.Name, build.WizardId);

            return sb.ToString().Replace("\r\n", "\n");
        }

        public static string Json(Ledger ledger)
        {
            var cat = ledger.Catalogue;
            var summary = new List<KeyValuePair<string, JsonValue>>();
            foreach (var (type, _) in Sections) summary.Add(Pair(ContentIds.JsonKey(type), SummaryJson(ledger, type)));
            summary.Add(Pair("all", SummaryJson(ledger, null)));

            var records = new List<JsonValue>();
            foreach (var entry in ledger.Entries)
            {
                var fields = new List<KeyValuePair<string, JsonValue>>
                {
                    Pair("id", entry.Record.Id),
                    Pair("type", entry.Record.Type.ToString().ToLowerInvariant()),
                    Pair("name", entry.Record.Name),
                    Pair("status", Ledger.Slug(entry.Status)),
                };
                if (entry.Record is SpellDef spell) fields.Add(Pair("wizard_id", spell.WizardId));
                if (entry.Record is AugmentDef augment && augment.IsTransformation)
                {
                    fields.Add(Pair("wizard_id", augment.OwnerWizardId));
                    fields.Add(Pair("target_spell_id", augment.TargetSpellId));
                }
                fields.Add(Pair("implemented_by", JsonValue.StringArray(entry.ImplementedBy)));
                fields.Add(Pair("verifying_tests", JsonValue.Array(entry.Tests.Select(t => JsonValue.Object(
                    ("test", t.Test), ("assembly", t.Assembly), ("outcome", OutcomeSlug(t.Outcome)))))));
                records.Add(JsonValue.Object(fields));
            }

            var root = JsonValue.Object(
                ("generated_by", "Confluence.Tools.Ledger"),
                ("regenerate", "powershell -ExecutionPolicy Bypass -File tools/ledger.ps1"),
                ("catalogue", JsonValue.Object(("title", cat.Title), ("design_version", cat.DesignVersion), ("date", cat.Date))),
                ("statuses", JsonValue.StringArray(Ledger.AllStatuses.Select(Ledger.Slug))),
                ("test_assemblies", JsonValue.StringArray(ledger.TestAssemblies)),
                ("trx_files", ledger.TrxFiles.Count),
                ("verifying_test_methods", ledger.VerifyingTestCount),
                ("out_of_scope_ids", JsonValue.StringArray(ledger.OutOfScopeIds)),
                ("unknown_ids", JsonValue.StringArray(ledger.UnknownIds)),
                ("summary", JsonValue.Object(summary)),
                ("records", JsonValue.Array(records)));
            return JsonWriter.Write(root, indented: true) + "\n";
        }

        private static JsonValue SummaryJson(Ledger ledger, ContentType? type)
        {
            var fields = new List<KeyValuePair<string, JsonValue>> { Pair("total", ledger.Count(type, null)) };
            foreach (var status in Ledger.AllStatuses) fields.Add(Pair(Ledger.Slug(status), ledger.Count(type, status)));
            return JsonValue.Object(fields);
        }

        private static void SummaryRow(StringBuilder sb, Ledger ledger, string title, ContentType? type)
        {
            sb.Append("| ").Append(title).Append(" | ").Append(ledger.Count(type, null)).Append(" |");
            foreach (var status in Ledger.AllStatuses) sb.Append(' ').Append(ledger.Count(type, status)).Append(" |");
            sb.AppendLine();
        }

        private static void Row(StringBuilder sb, LedgerEntry entry, params string[] columns)
        {
            sb.Append("| ").Append(entry.Record.Id).Append(" |");
            foreach (var column in columns) sb.Append(' ').Append(Cell(column)).Append(" |");
            sb.Append(' ').Append(Ledger.Slug(entry.Status)).Append(" | ").Append(Evidence(entry)).AppendLine(" |");
        }

        private static string Evidence(LedgerEntry entry)
        {
            var parts = new List<string>();
            if (entry.ImplementedBy.Count > 0) parts.Add(string.Join(", ", entry.ImplementedBy.Select(ShortName)));
            if (entry.Tests.Count > 0)
            {
                int passed = entry.Tests.Count(t => t.Outcome == TestOutcome.Passed);
                int failed = entry.Tests.Count(t => t.Outcome == TestOutcome.Failed);
                string text = passed + "/" + entry.Tests.Count + " tests passed";
                if (failed > 0) text += ", " + failed + " failed";
                parts.Add(text);
            }
            return Cell(string.Join("; ", parts));
        }

        private static string ShortName(string fullName)
        {
            int dot = fullName.LastIndexOf('.');
            return dot < 0 ? fullName : fullName.Substring(dot + 1);
        }

        private static string OutcomeSlug(TestOutcome outcome)
        {
            switch (outcome)
            {
                case TestOutcome.Passed: return "passed";
                case TestOutcome.Failed: return "failed";
                default: return "not-run";
            }
        }

        private static string Cell(string text) => (text ?? "").Replace("|", "\\|").Replace("\r", " ").Replace("\n", " ");

        private static KeyValuePair<string, JsonValue> Pair(string key, JsonValue value) => new KeyValuePair<string, JsonValue>(key, value);
    }
}
