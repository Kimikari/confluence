using System;
using System.Globalization;
using Confluence.Arena.Generation;
using Confluence.Core.Rules;

namespace Confluence.Client.App
{
    /// <summary>Which camera the arena preview starts with.</summary>
    public enum PreviewView
    {
        /// <summary>Free-fly camera at an elevated establishing position.</summary>
        Fly,

        /// <summary>First-person walk from spawn side 0.</summary>
        Walk,

        /// <summary>Rotatable top-down overview (spec L329).</summary>
        Overview,
    }

    /// <summary>Main-menu entry opened at start, so smoke screenshots can cover every menu screen.</summary>
    public enum MenuPanel
    {
        None,

        /// <summary>The Play card (host, port, display name).</summary>
        Play,

        /// <summary>The settings overlay.</summary>
        Settings,

        /// <summary>The Codex screen.</summary>
        Codex,

        /// <summary>The Training screen.</summary>
        Training,
    }

    /// <summary>Laboratory screen opened at start by -laboratory (smoke screenshots of every M1 screen).</summary>
    public enum LabScreen
    {
        Setup,
        Reveal,
        Shop,
        Draft,
        Build,
        Duel,
        Results,
    }

    /// <summary>
    /// Player command-line switches for previews and automated smoke tests (Unity's own switches such as
    /// -screen-width are ignored here):
    /// <list type="bullet">
    /// <item>-arenaPreview: skip the menu and open the arena preview (generated by Confluence.Arena).</item>
    /// <item>-previewView fly|walk|overview: starting preview camera (default fly).</item>
    /// <item>-previewTime &lt;seconds&gt;: initial preview clock, -5 (alcove phase, the default) to 90 (combat end).</item>
    /// <item>-arenaSeed &lt;n&gt;, -arenaRound &lt;n&gt;, -arenaDiameter 24|32|40|48, -arenaBiome BIO-nnn: generator request for the
    /// preview and the Laboratory (default seed 7919, round 1, scheduled diameter, seeded biome).</item>
    /// <item>-menuPanel play|settings|codex|training: open that main-menu entry at start.</item>
    /// <item>-laboratory: open the offline Laboratory; -labScreen setup|reveal|shop|draft|build|duel|results picks the
    /// screen, -labRound &lt;n&gt; the starting round, -labWizard/-labOpponent WIZ-nnn the wizards, -labDuelTime &lt;s&gt;
    /// fast-forwards the sandbox duel, -labDemo applies the scripted demonstration state (smoke screenshots).</item>
    /// <item>-screenshot &lt;path&gt;: write a PNG of the screen shortly before quitting (or after 3 s).</item>
    /// <item>-quitAfter &lt;seconds&gt;: quit after this much real time; the exit code is 1 if errors were logged.</item>
    /// </list>
    /// </summary>
    public sealed class CommandLineOptions
    {
        public const float DefaultPreviewTimeSec = -GlobalRules.Round.AlcoveSec;
        public const ulong DefaultArenaSeed = 7919;

        public bool ArenaPreview { get; private set; }
        public PreviewView PreviewView { get; private set; } = PreviewView.Fly;
        public MenuPanel MenuPanel { get; private set; } = MenuPanel.None;

        /// <summary>Initial preview clock; defaults to the start of the 5 s alcove phase (spec L46).</summary>
        public float PreviewTimeSec { get; private set; } = DefaultPreviewTimeSec;

        public ulong ArenaSeed { get; private set; } = DefaultArenaSeed;
        public int ArenaRound { get; private set; } = 1;

        /// <summary>Forced diameter, or 0 for the round's slot in the balanced schedule (spec L306).</summary>
        public int ArenaDiameter { get; private set; }

        /// <summary>Forced biome id, or null for the seeded choice (spec L316).</summary>
        public string ArenaBiome { get; private set; }

        public bool Laboratory { get; private set; }
        public LabScreen LabScreen { get; private set; } = LabScreen.Setup;
        public int LabRound { get; private set; } = 1;
        public string LabWizard { get; private set; }
        public string LabOpponent { get; private set; }

        /// <summary>Combat seconds to fast-forward the Laboratory duel to, or a negative value for none.</summary>
        public float LabDuelTimeSec { get; private set; } = -1f;

        public bool LabDemo { get; private set; }

        public string ScreenshotPath { get; private set; }

        /// <summary>Seconds of real time before quitting; 0 or less disables the timer.</summary>
        public float QuitAfterSec { get; private set; }

        /// <summary>Unrecognized or malformed switches, for logging.</summary>
        public string Warnings { get; private set; } = string.Empty;

        public bool IsSmokeTest => ScreenshotPath != null || QuitAfterSec > 0f;

        /// <summary>The arena generator request described by the -arena* switches.</summary>
        public ArenaRequest ArenaRequest => new ArenaRequest
        {
            MatchSeed = ArenaSeed,
            Round = ArenaRound,
            Diameter = ArenaDiameter,
            BiomeId = ArenaBiome,
        };

        public static CommandLineOptions FromEnvironment() => Parse(Environment.GetCommandLineArgs());

        public static CommandLineOptions Parse(string[] args)
        {
            var options = new CommandLineOptions();
            if (args == null)
            {
                return options;
            }

            for (int i = 0; i < args.Length; i++)
            {
                string arg = args[i];
                bool hasValue = i + 1 < args.Length;
                if (Is(arg, "-arenaPreview"))
                {
                    options.ArenaPreview = true;
                }
                else if (Is(arg, "-laboratory"))
                {
                    options.Laboratory = true;
                }
                else if (Is(arg, "-labDemo"))
                {
                    options.LabDemo = true;
                }
                else if (Is(arg, "-previewView") && hasValue)
                {
                    options.PreviewView = ParseEnum(args[++i], "-previewView", options, options.PreviewView);
                }
                else if (Is(arg, "-menuPanel") && hasValue)
                {
                    options.MenuPanel = ParseEnum(args[++i], "-menuPanel", options, options.MenuPanel);
                }
                else if (Is(arg, "-labScreen") && hasValue)
                {
                    options.LabScreen = ParseEnum(args[++i], "-labScreen", options, options.LabScreen);
                }
                else if (Is(arg, "-previewTime") && hasValue)
                {
                    // Negative values down to -5 are the alcove phase (spec L46); the preview clamps the range.
                    options.PreviewTimeSec = ParseSeconds(args[++i], "-previewTime", options, allowNegative: true, fallback: DefaultPreviewTimeSec);
                }
                else if (Is(arg, "-labDuelTime") && hasValue)
                {
                    options.LabDuelTimeSec = ParseSeconds(args[++i], "-labDuelTime", options, fallback: -1f);
                }
                else if (Is(arg, "-arenaSeed") && hasValue)
                {
                    string text = args[++i];
                    if (ulong.TryParse(text, NumberStyles.Integer, CultureInfo.InvariantCulture, out ulong seed))
                    {
                        options.ArenaSeed = seed;
                    }
                    else
                    {
                        options.Warnings += "Ignoring -arenaSeed '" + text + "'. ";
                    }
                }
                else if (Is(arg, "-arenaRound") && hasValue)
                {
                    options.ArenaRound = ParseInt(args[++i], "-arenaRound", options, 1, ArenaSchedule.ScheduledRoundCapacity, options.ArenaRound);
                }
                else if (Is(arg, "-labRound") && hasValue)
                {
                    options.LabRound = ParseInt(args[++i], "-labRound", options, 1, GlobalRules.Match.RegularRounds, options.LabRound);
                }
                else if (Is(arg, "-arenaDiameter") && hasValue)
                {
                    string text = args[++i];
                    if (int.TryParse(text, NumberStyles.Integer, CultureInfo.InvariantCulture, out int diameter) && Schedules.IsValidArenaDiameter(diameter))
                    {
                        options.ArenaDiameter = diameter;
                    }
                    else
                    {
                        options.Warnings += "Ignoring -arenaDiameter '" + text + "' (24, 32, 40, or 48). ";
                    }
                }
                else if (Is(arg, "-arenaBiome") && hasValue)
                {
                    options.ArenaBiome = args[++i];
                }
                else if (Is(arg, "-labWizard") && hasValue)
                {
                    options.LabWizard = args[++i];
                }
                else if (Is(arg, "-labOpponent") && hasValue)
                {
                    options.LabOpponent = args[++i];
                }
                else if (Is(arg, "-screenshot") && hasValue)
                {
                    options.ScreenshotPath = args[++i];
                }
                else if (Is(arg, "-quitAfter") && hasValue)
                {
                    options.QuitAfterSec = ParseSeconds(args[++i], "-quitAfter", options);
                }
            }

            return options;
        }

        private static bool Is(string arg, string name) => string.Equals(arg, name, StringComparison.OrdinalIgnoreCase);

        private static T ParseEnum<T>(string text, string name, CommandLineOptions options, T fallback) where T : struct
        {
            if (Enum.TryParse(text, true, out T value) && Enum.IsDefined(typeof(T), value))
            {
                return value;
            }

            options.Warnings += "Unknown " + name + " '" + text + "'. ";
            return fallback;
        }

        private static int ParseInt(string text, string name, CommandLineOptions options, int min, int max, int fallback)
        {
            if (int.TryParse(text, NumberStyles.Integer, CultureInfo.InvariantCulture, out int value) && value >= min && value <= max)
            {
                return value;
            }

            options.Warnings += "Ignoring " + name + " '" + text + "' (" + min + "-" + max + "). ";
            return fallback;
        }

        private static float ParseSeconds(string text, string name, CommandLineOptions options, bool allowNegative = false, float fallback = 0f)
        {
            if (float.TryParse(text, NumberStyles.Float, CultureInfo.InvariantCulture, out float value)
                && !float.IsNaN(value) && !float.IsInfinity(value) && (allowNegative || value >= 0f))
            {
                return value;
            }

            options.Warnings += "Ignoring " + name + " '" + text + "'. ";
            return fallback;
        }
    }
}
